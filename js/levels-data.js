  addLevel(levelNum, title, stageName, questions) {
    this.levels[levelNum] = {
      level: levelNum,
      title: title,
      stageName: stageName,
      questionsCount: questions.length,
      questions: questions
    };
  }

  // स्तर प्राप्त करना
  getLevel(levelNum) {
    return this.levels[levelNum] || null;
  }

  // कुल स्तर संख्या
  getTotalLevels() {
    return Object.keys(this.levels).length;
  }

  // सहायक: सरणी शफ़ल
  shuffleArray(arr) {
    const array = [...arr];
    for (let i = array.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [array[i], array[j]] = [array[j], array[i]];
    }
    return array;
  }

  // सहायक: विकल्प शफ़ल
  shuffleOptions(options) {
    const unique = Array.from(new Set(options));
    return this.shuffleArray(unique);
  }
